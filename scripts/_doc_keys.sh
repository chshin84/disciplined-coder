# 문서 계약 검사가 산문 문장 대신 붙드는 안정된 열쇠를 읽는 함수들이다. 검사 스크립트가 source 한다.
# 문장 끝이나 낱말을 고쳐도 조항 ID·절 제목·소유 선언·포인터가 그대로면 검사가 통과하고, 그 열쇠가
# 사라지거나 이름이 바뀌면 실패한다.
#
# 절 이름은 제목 전체와 같거나, 제목이 그 이름 뒤에 " (" 나 " —" 를 달고 이어질 때 같은 절로 본다.
# 이 레포는 이름 뒤에 설명절을 다는 제목이 많아 전체 일치만 보면 설명절을 붙이는 순간 실패한다.
# 앞부분 일치로 넓히지 않는 이유는 「기록」과 「기록 파일 이름 규칙」처럼 이름이 겹치는 절이 있어서다.
# 코드 펜스 안의 '#' 줄은 제목이 아니므로 건너뛴다.
#
# pipefail 아래에서 `printf | grep -q` 는 grep 이 먼저 끝나 앞 명령이 EPIPE 로 실패할 수 있다. 그래서
# 모두 here-string 으로 넘긴다.

doc_sec() {  # $1=파일 $2=절 이름 → 그 절의 본문(제목 줄 포함). 같은 단계 이상의 다음 제목 앞에서 멈춘다.
  LC_ALL=C.UTF-8 awk -v name="$2" '
    { sub(/\r$/, "") }
    /^```/ { fence = !fence }
    !fence && /^#+ / {
      lvl = match($0, /[^#]/) - 1
      t = $0; sub(/^#+ +/, "", t)
      if (f && lvl <= flvl) exit
      if (!f && (t == name || index(t, name " (") == 1 || index(t, name " —") == 1)) { f = 1; flvl = lvl }
    }
    f' "$1"
}
has_sec()    { [ -n "$(doc_sec "$1" "$2")" ]; }                          # 절이 있다
sec_has()    { grep -qF -- "$3" <<<"$(doc_sec "$1" "$2")"; }             # 절 안에 문자열 $3 이 있다
sec_has_id() { sec_has "$1" "$2" "\`$3\`"; }                             # 절 안에 백틱 식별자 $3 이 있다
owns_sec()   { sec_has "$1" "$2" '소유'; }                               # 절이 있고 그 안에서 소유를 밝힌다
has_clause() { grep -qF -- "**\`$2\`" "$1"; }                            # 에이전트원칙 꼴의 굵은 조항 ID 가 있다
# 한 줄에 소유자 이름과 절 이름이 함께 있다. 파일 단위로 보면 소유자를 다른 곳에서 한 번 부른 문서가
# 이 포인터를 빠뜨려도 통과한다.
points_to()  { grep -qF -- "$2" <<<"$(grep -F -- "$3" "$1")"; }         # $1=파일 $2=소유자 이름 $3=절 이름
