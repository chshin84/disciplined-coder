#!/usr/bin/env bash
# 공유: 훅 응답의 JSON 문자열 값을 이스케이프한다. 소비자는 이 파일을 source하는 모든 훅이다.
# 역슬래시와 큰따옴표만 다루던 sed 한 줄을 대신한다 — 파일명에 개행이나 탭이 섞이면 제어 문자가
# JSON 문자열에 날것으로 들어가 응답이 파싱되지 않고, 그러면 차단 결정이 통째로 무시된다(FAIL-LOUD).
# 순수 bash 문자열 치환이라 외부 의존이 없다.
escape_for_json() {
  local s="$1"
  s="${s//\\/\\\\}"; s="${s//\"/\\\"}"; s="${s//$'\n'/\\n}"; s="${s//$'\r'/\\r}"; s="${s//$'\t'/\\t}"
  printf '%s' "$s"
}
